package stringsx

import (
	"bytes"
	"fmt"
	"os"
	"testing"
	"unicode"
)

// updateFindFoldTable rewrites the tables instead of checking them.
var updateFindFoldTable = os.Getenv("FIND_FOLD_TABLE_UPDATE") == "1"

// The find fold tables, Go's and the frontend's, are generated from
// package unicode's simple lower case and checked in, so the find rule
// does not follow a runtime's or a browser's own case tables. Go's
// Unicode version moving makes this fail until the tables are rewritten
// with FIND_FOLD_TABLE_UPDATE=1.
func TestFindFoldTablesAreCurrent(t *testing.T) {
	ranges := findFoldRangesFromUnicode(t)
	files := map[string][]byte{
		"findfold_table.go":                             renderGoFindFoldTable(ranges),
		"../../frontend/src/lib/utils/findFoldTable.ts": renderTSFindFoldTable(ranges),
	}
	for path, want := range files {
		if updateFindFoldTable {
			if err := os.WriteFile(path, want, 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		got, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(got, want) {
			t.Errorf("%s is not the table package unicode %s gives; rerun with FIND_FOLD_TABLE_UPDATE=1", path, unicode.Version)
		}
	}
	if FindFoldUnicodeVersion != unicode.Version {
		t.Errorf("table is Unicode %s, package unicode is %s", FindFoldUnicodeVersion, unicode.Version)
	}
}

// Every code point folds by the table as unicode.ToLower folds it.
func TestFindFoldTableIsUnicodeToLower(t *testing.T) {
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if got, want := foldRune(r), unicode.ToLower(r); got != want {
			t.Fatalf("U+%04X folds to U+%04X, unicode.ToLower gives U+%04X", r, got, want)
		}
	}
}

// findFoldRangesFromUnicode is every code point unicode.ToLower changes,
// as runs of one delta at a stride of one or two.
func findFoldRangesFromUnicode(t *testing.T) []foldRange {
	var out []foldRange
	for r := rune(0); r <= unicode.MaxRune; r++ {
		l := unicode.ToLower(r)
		if l == r {
			continue
		}
		if (r >= 0x10000) != (l >= 0x10000) {
			t.Fatalf("U+%04X lowers to U+%04X across planes; the frontend's UTF-16 offsets would move", r, l)
		}
		d := l - r
		if n := len(out); n > 0 {
			last := &out[n-1]
			if last.delta == d && last.lo == last.hi && (r == last.hi+1 || r == last.hi+2) {
				last.stride = r - last.hi
				last.hi = r
				continue
			}
			if last.delta == d && r == last.hi+last.stride {
				last.hi = r
				continue
			}
		}
		out = append(out, foldRange{lo: r, hi: r, delta: d, stride: 1})
	}
	return out
}

func renderGoFindFoldTable(ranges []foldRange) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by TestFindFoldTablesAreCurrent; DO NOT EDIT.\n\npackage stringsx\n\n")
	fmt.Fprintf(&b, "// FindFoldUnicodeVersion is the Unicode version of the find fold table.\nconst FindFoldUnicodeVersion = %q\n\n", unicode.Version)
	b.WriteString("// findFoldRanges is every code point the find rule folds: lo..hi at\n// stride, each to itself plus delta.\nvar findFoldRanges = []foldRange{\n")
	for _, r := range ranges {
		fmt.Fprintf(&b, "\t{0x%04X, 0x%04X, %d, %d},\n", r.lo, r.hi, r.delta, r.stride)
	}
	b.WriteString("}\n")
	return b.Bytes()
}

func renderTSFindFoldTable(ranges []foldRange) []byte {
	var b bytes.Buffer
	b.WriteString("// Generated from Go's package unicode by internal/stringsx\n// TestFindFoldTablesAreCurrent; do not edit.\n\n")
	fmt.Fprintf(&b, "/** The Unicode version of the find fold table. */\nexport const FIND_FOLD_UNICODE_VERSION = '%s';\n\n", unicode.Version)
	b.WriteString("/** Every code point the find rule folds, as (lo, hi, delta, stride)\n * runs in code point order: lo..hi at stride, each to itself plus delta. */\n")
	b.WriteString("export const FIND_FOLD_RANGES = new Int32Array([\n")
	for _, r := range ranges {
		fmt.Fprintf(&b, "  0x%04x, 0x%04x, %d, %d,\n", r.lo, r.hi, r.delta, r.stride)
	}
	b.WriteString("]);\n")
	return b.Bytes()
}

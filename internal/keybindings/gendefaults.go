package keybindings

//go:generate go run ./gendefaults

import "encoding/json"

const FrontendDefaultsRelPath = "../../frontend/src/lib/generated/keybindingDefaults.ts"

// FrontendDefaultsSource keeps offline frontends on the same shipped shortcuts
// as desktop, including the stable row identities and reset chords.
func FrontendDefaultsSource() string {
	data, err := json.MarshalIndent(Merge(Defaults, nil), "", "  ")
	if err != nil {
		panic(err) // Keybinding contains only strings.
	}
	return "// Code generated by go generate ./internal/keybindings; DO NOT EDIT.\n" +
		"import type { KeybindingRule } from '../stores/keybindings.svelte';\n\n" +
		"export const KEYBINDING_DEFAULTS: readonly KeybindingRule[] = " + string(data) + ";\n"
}

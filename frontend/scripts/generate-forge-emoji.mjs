#!/usr/bin/env node
// Generate the forge emoji shortcode table, `src/lib/utils/forgeEmojiTable.ts`.
//
//   cd frontend
//   node scripts/generate-forge-emoji.mjs
//
// Sources, pinned so a rerun reproduces the checked-in table:
//
//   GitHub  gemoji v4.1.0 `db/emoji.json` (MIT, GitHub, Inc.): every alias
//           of every character. GitHub's image-only emoji are not in it;
//           their names are GITHUB_IMAGES below, the entries GitHub's
//           emoji list maps to `images/icons/emoji/<name>.png`.
//   GitLab  GitLab v18.6.0-ee `fixtures/emojis/digests.json` (names and
//           characters) and `aliases.json` (alias to name), generated from
//           the tanuki_emoji gem GitLab renders with (MIT, GitLab Inc.).
//           The ASCII aliases (`:) `) are not shortcodes and are dropped.
//
// License texts: src/lib/utils/FORGE_EMOJI_LICENSE.
//
// Output: one line per character, `<character> <name> <name>...`. A name
// both forges map to that character is bare; `!name` is GitHub's only and
// `?name` GitLab's only, so a name the two forges map to different
// characters appears on two lines. utils/forgeEmoji.ts decodes it.

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const GEMOJI = 'https://raw.githubusercontent.com/github/gemoji/v4.1.0/db/emoji.json';
const GITLAB_FIXTURES = 'https://gitlab.com/gitlab-org/gitlab/-/raw/v18.6.0-ee/fixtures/emojis';

const GITHUB_IMAGES = [
  'accessibility', 'atom', 'basecamp', 'basecampy', 'bowtie', 'dependabot', 'electron', 'feelsgood',
  'finnadie', 'fishsticks', 'goberserk', 'godmode', 'hurtrealbad', 'neckbeard', 'octocat', 'rage1',
  'rage2', 'rage3', 'rage4', 'shipit', 'suspect', 'trollface',
];

const NAME = /^[a-z0-9_+-]+$/;

async function json(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.json();
}

function checkName(name, source) {
  if (!NAME.test(name)) throw new Error(`${source}: unexpected shortcode name ${JSON.stringify(name)}`);
}

const [gemoji, digests, aliases] = await Promise.all([
  json(GEMOJI),
  json(`${GITLAB_FIXTURES}/digests.json`),
  json(`${GITLAB_FIXTURES}/aliases.json`),
]);

/** @type {Map<string, string>} */
const github = new Map();
for (const entry of gemoji) {
  for (const name of entry.aliases) {
    checkName(name, 'gemoji');
    github.set(name, entry.emoji);
  }
}
/** @type {Map<string, string>} */
const gitlab = new Map();
for (const [name, entry] of Object.entries(digests)) {
  checkName(name, 'digests.json');
  gitlab.set(name, entry.moji);
}
for (const [alias, name] of Object.entries(aliases)) {
  if (alias.endsWith(' ')) continue;
  checkName(alias, 'aliases.json');
  const moji = digests[name]?.moji;
  if (moji === undefined) throw new Error(`aliases.json: ${alias} names unknown ${name}`);
  if (!gitlab.has(alias)) gitlab.set(alias, moji);
}

// Characters in first-seen order, GitHub's then GitLab's.
/** @type {Map<string, string[]>} */
const lines = new Map();
const add = (moji, name) => {
  let names = lines.get(moji);
  if (!names) lines.set(moji, (names = []));
  names.push(name);
};
for (const [name, moji] of github) add(moji, gitlab.get(name) === moji ? name : `!${name}`);
for (const [name, moji] of gitlab) if (github.get(name) !== moji) add(moji, `?${name}`);

const table = [...lines].map(([moji, names]) => `${moji} ${names.join(' ')}`).join('\n');
const out = `// Generated by scripts/generate-forge-emoji.mjs from gemoji and GitLab's
// emoji fixtures; do not edit. Sources and licenses: FORGE_EMOJI_LICENSE.

/** \`<character> <name>...\`, one per line; \`!name\` GitHub only, \`?name\` GitLab only. */
export const SHORTCODES = ${JSON.stringify(table)};

/** GitHub's image-only emoji, space separated. */
export const GITHUB_IMAGES = ${JSON.stringify(GITHUB_IMAGES.join(' '))};
`;
const target = join(dirname(fileURLToPath(import.meta.url)), '../src/lib/utils/forgeEmojiTable.ts');
writeFileSync(target, out);
console.log(`${target}: GitHub ${github.size + GITHUB_IMAGES.length} names, GitLab ${gitlab.size}, ${lines.size} characters, ${out.length} chars`);
